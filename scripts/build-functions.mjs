// Inline functions/src/_shared.ts into each function so every deploy is one
// self-contained file (InsForge deploys a single file per function).
// Usage: node scripts/build-functions.mjs   -> writes functions/dist/<slug>.ts

import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const src = join(import.meta.dirname, '..', 'functions', 'src');
const dist = join(import.meta.dirname, '..', 'functions', 'dist');
mkdirSync(dist, { recursive: true });

const shared = readFileSync(join(src, '_shared.ts'), 'utf8');

for (const file of readdirSync(src)) {
  if (file.startsWith('_') || !file.endsWith('.ts')) continue;
  const code = readFileSync(join(src, file), 'utf8');
  const body = code.replace(/^import\s*\{[^}]*\}\s*from\s*'\.\/_shared\.ts';\s*$/m, '');
  if (body === code) throw new Error(`${file}: expected an import from './_shared.ts'`);
  writeFileSync(
    join(dist, file),
    `// GENERATED by scripts/build-functions.mjs from functions/src/${file} - do not edit.\n\n` +
      `// ---- shared ----\n${shared}\n// ---- ${file} ----\n${body}`,
  );
  console.log('built', file);
}
