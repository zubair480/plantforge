// Inline functions/src/_logic.ts and _shared.ts into each function so every
// deploy is one self-contained file (InsForge deploys a single file per function).
// Usage: node scripts/build-functions.mjs   -> writes functions/dist/<slug>.ts

import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const src = join(import.meta.dirname, '..', 'functions', 'src');
const dist = join(import.meta.dirname, '..', 'functions', 'dist');
mkdirSync(dist, { recursive: true });

// Matches `import { a, b } from './_shared.ts';` (and _logic), possibly over several lines.
const localImport = (name) => new RegExp(`^import\\s*\\{[^}]*\\}\\s*from\\s*'\\./${name}\\.ts';[ \\t]*\\r?\\n?`, 'm');
const strip = (code, name) => code.replace(localImport(name), '');

const logic = readFileSync(join(src, '_logic.ts'), 'utf8');
const shared = strip(readFileSync(join(src, '_shared.ts'), 'utf8'), '_logic');

for (const file of readdirSync(src)) {
  if (file.startsWith('_') || !file.endsWith('.ts')) continue;
  const code = readFileSync(join(src, file), 'utf8');
  const body = strip(strip(code, '_shared'), '_logic');
  if (!localImport('_shared').test(code)) throw new Error(`${file}: expected an import from './_shared.ts'`);
  if (/from\s*'\.\/(?!_shared|_logic)/.test(body)) throw new Error(`${file}: only ./_shared.ts and ./_logic.ts can be imported`);
  writeFileSync(
    join(dist, file),
    `// GENERATED by scripts/build-functions.mjs from functions/src/${file} - do not edit.\n\n` +
      `// ---- logic ----\n${logic}\n// ---- shared ----\n${shared}\n// ---- ${file} ----\n${body}`,
  );
  console.log('built', file);
}
